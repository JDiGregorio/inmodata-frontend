const { chromium } = require('playwright')
const { build } = require('esbuild')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const http = require('node:http')

async function main() {
    const tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'inmodata-property-view-'))
    const result = await build({ entryPoints: [path.join(__dirname, 'property-view-harness.tsx')], bundle: true, write: false, jsx: 'automatic',
        loader: { '.png': 'dataurl' }, define: { 'process.env.NODE_ENV': '"test"', 'import.meta.env.APP_BASE_URL': '""' }, logLevel: 'silent',
        plugins: [{ name: 'maps-sdk-only', setup(builder) {
            builder.onResolve({ filter: /^@vis.gl\/react-google-maps$/ }, () => ({ path: path.join(__dirname, 'maps-sdk-stub.tsx') }))
            builder.onResolve({ filter: /\/Circle$/ }, () => ({ path: 'circle', namespace: 'test-circle' }))
            builder.onLoad({ filter: /.*/, namespace: 'test-circle' }, () => ({ contents: 'export const Circle = () => null', loader: 'js' }))
        } }] })
    const assets = await fs.readdir('dist/assets')
    const css = await fs.readFile(path.join('dist/assets', assets.find(file => file.endsWith('.css'))))
    const server = http.createServer((req, res) => {
        if (req.url === '/app.js') { res.setHeader('Content-Type', 'text/javascript'); return res.end(result.outputFiles[0].text) }
        if (req.url === '/app.css') { res.setHeader('Content-Type', 'text/css'); return res.end(css) }
        res.setHeader('Content-Type', 'text/html')
        res.end('<html><head><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="/app.css"></head><body><div id="root"></div><script src="/app.js"></script></body></html>')
    })
    let browser
    try {
        await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
        browser = await chromium.launch({ channel: 'chrome', headless: true })
        const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
        const errors = []
        page.on('pageerror', error => errors.push(error.message))
        const base = `http://127.0.0.1:${server.address().port}`
        await page.goto(base)
        await page.getByTestId('map').waitFor()
        assert.deepEqual(await page.locator('dt').allTextContents(), ['Referencia', 'Clave Catastral', 'Dirección', 'Latitud', 'Longitud'])
        assert.equal(await page.getByText('INMO000656', { exact: true }).count(), 1)
        const fields = await page.locator('dl > div').evaluateAll(nodes => nodes.map(node => { const r = node.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width } }))
        assert.equal(fields[0].y, fields[1].y)
        assert.ok(fields[2].y > fields[0].y && fields[2].width > fields[0].width * 1.8)
        assert.equal(fields[3].y, fields[4].y)
        assert.ok(fields[3].y > fields[2].y)
        assert.equal(await page.getByTestId('map').getAttribute('data-center'), '{"lat":14.1,"lng":-87.2}')
        assert.equal(await page.getByTestId('map').getAttribute('data-zoom'), '20')
        assert.equal(await page.getByTestId('marker').getAttribute('data-position'), '{"lat":14.1,"lng":-87.2}')
        assert.equal(await page.getByTestId('marker').getAttribute('data-draggable'), 'false')
        assert.equal(await page.getByTestId('marker').getAttribute('data-drag-handler'), 'false')
        assert.equal(await page.getByTestId('map').getAttribute('data-click-handler'), 'false')
        assert.equal(await page.getByAltText('Ubicación del inmueble').evaluate(img => img.complete && img.naturalWidth > 0), true)
        await page.getByTestId('map').click({ position: { x: 10, y: 10 } })
        await page.getByTestId('marker').dblclick()
        assert.deepEqual(await page.locator('dd').allTextContents(), ['INMO000656', 'CAD-A', 'Dirección completa del inmueble de prueba', '14.1', '-87.2'])
        assert.deepEqual(await page.evaluate(() => window.viewRequests), ['GetPropertyById'])
        assert.equal(await page.locator('input,textarea').count(), 0)
        const link = page.getByRole('link', { name: 'Ver en mapa' })
        const style = await link.getAttribute('class')
        const href = await link.getAttribute('href')
        await page.screenshot({ path: path.join(tmp, 'view-desktop.png'), fullPage: true })
        for (const width of [390, 768]) {
            await page.setViewportSize({ width, height: 900 })
            await page.evaluate(() => window.scrollTo(0, 0))
            await page.waitForTimeout(250)
            assert.equal(await page.locator('h1').count(), 1)
            assert.equal(await page.getByText('INMO000656', { exact: true }).count(), 1)
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
            const box = await page.getByTestId('map').boundingBox()
            assert.ok(box.width > 200 && box.height > 200)
            await page.screenshot({ path: path.join(tmp, `view-${width}.png`), fullPage: true })
        }
        await page.goto(`${base}/?private=1`)
        await page.getByTestId('map').waitFor()
        assert.equal(await page.locator('dl > div').nth(1).locator('dd').textContent(), '-')
        await page.goto(`${base}/?missing=1`)
        await page.getByText('Ubicación no disponible.').waitFor()
        assert.equal(await page.getByTestId('map').count(), 0)
        assert.equal(await page.getByRole('button', { name: 'Ver en mapa' }).isDisabled(), true)
        await page.goto(`${base}/?denied=1`)
        await page.getByText('Error 404', { exact: true }).waitFor()
        assert.equal(await page.getByTestId('map').count(), 0)
        await page.goto(`${base}/?edit=1`)
        await page.getByTestId('map').waitFor()
        assert.equal(await link.getAttribute('class'), style)
        assert.equal(await link.getAttribute('href'), href)
        assert.equal(await page.getByTestId('marker').getAttribute('data-draggable'), 'true')
        await page.goto(`${base}/?editableMap=1`)
        await page.getByTestId('map').click({ position: { x: 10, y: 10 } })
        assert.equal(await page.locator('output').textContent(), '{"lat":15,"lng":-88}')
        await page.getByTestId('marker').dblclick()
        assert.equal(await page.locator('output').textContent(), '{"lat":16,"lng":-89}')
        assert.deepEqual(errors, [])
        console.log(`PASS: field order/layout, readonly map/marker, no mutations/proximity query, missing/private/denied states, shared Edit button, editable map regression. SDK tiles mocked. Screenshots: ${tmp}`)
    } finally {
        await browser?.close()
        await new Promise(resolve => server.close(resolve))
    }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
