// Run with Playwright available through NODE_PATH; no production dependency is required.
const { chromium } = require('playwright')
const { build } = require('esbuild')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const http = require('node:http')

async function main() {
    const tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'inmodata-institutions-'))
    let browser
    let server
    try {
        await build({ entryPoints: [path.join(__dirname, 'institution-harness.tsx')], bundle: true, outfile: path.join(tmp, 'app.js'), jsx: 'automatic', loader: { '.png': 'dataurl' },
            plugins: [{ name: 'isolate-property-map', setup(build) {
                build.onLoad({ filter: /InmuebleMapPreview\.tsx$/ }, () => ({ contents: 'export function InmuebleMapPreview() { return null }', loader: 'tsx' }))
            } }],
            define: { 'process.env.NODE_ENV': '"test"', 'import.meta.env.APP_BASE_URL': '""' }, logLevel: 'silent' })
        const assets = await fs.readdir('dist/assets')
        const css = await fs.readFile(path.join('dist/assets', assets.find((name) => name.endsWith('.css'))))
        const js = await fs.readFile(path.join(tmp, 'app.js'))
        server = http.createServer((req, res) => {
            if (req.url === '/app.js') { res.setHeader('Content-Type', 'text/javascript'); return res.end(js) }
            if (req.url === '/app.css') { res.setHeader('Content-Type', 'text/css'); return res.end(css) }
            res.setHeader('Content-Type', 'text/html')
            res.end('<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="/app.css"></head><body><div id="root"></div><div id="modal-container"></div><script src="/app.js"></script></body></html>')
        })
        await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve))
        const url = `http://127.0.0.1:${server.address().port}`
        browser = await chromium.launch({ channel: 'chrome', headless: true })
        const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
        const errors = []
        page.on('pageerror', (error) => errors.push(error.message))
        const requests = (name) => page.evaluate((name) => window.institutionTestRequests.filter((request) => request.name === name), name)

        await page.goto(url)
        const toggle = page.getByRole('button', { name: /Otras valuaciones disponibles/ })
        await toggle.waitFor()
        assert.equal(await toggle.getAttribute('aria-expanded'), 'false')
        assert.equal((await requests('PropertyExternalValuations')).length, 0)
        await toggle.click()
        await page.getByText('Solo lectura', { exact: true }).waitFor()
        assert.equal(await page.getByText('1,234.40', { exact: true }).count(), 1)
        assert.equal(await page.getByRole('button', { name: /Editar|Eliminar|Guardar/ }).count(), 0)
        await page.getByRole('button', { name: 'Página siguiente' }).click()
        await page.getByText('Banco C', { exact: true }).waitFor()
        await toggle.click()
        assert.equal(await page.getByText('Solo lectura', { exact: true }).count(), 0)
        await page.screenshot({ path: path.join(tmp, 'panel-desktop.png') })
        await page.setViewportSize({ width: 390, height: 844 })
        await toggle.click()
        await page.getByText('Solo lectura', { exact: true }).waitFor()
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
        await page.screenshot({ path: path.join(tmp, 'panel-mobile.png') })
        console.log('PASS: panel collapsed by default, explicit loading, pagination, readonly actions, mobile width')

        await page.goto(`${url}/?screen=edit`)
        await page.getByText('Banco A', { exact: false }).first().waitFor()
        await page.getByRole('button', { name: 'Seleccionar opciones' }).click()
        await page.getByRole('option', { name: 'Banco B' }).click()
        await page.getByRole('button', { name: 'Guardar', exact: true }).click()
        await page.waitForFunction(() => window.institutionTestRequests.some((request) => request.name === 'UpdateUser'))
        assert.deepEqual((await requests('UpdateUser'))[0].variables.input.institutionIds, ['1', '2'])
        console.log('PASS: edit preloads institutions and saves multiple assignments')

        await page.goto(`${url}/?screen=edit`)
        await page.getByRole('button', { name: 'Remove', exact: true }).click()
        await page.getByRole('button', { name: 'Guardar', exact: true }).click()
        await page.getByRole('button', { name: 'Confirmar', exact: true }).waitFor()
        assert.equal((await requests('UpdateUser')).length, 0)
        await page.getByRole('button', { name: 'Confirmar', exact: true }).click()
        await page.waitForFunction(() => window.institutionTestRequests.some((request) => request.name === 'UpdateUser'))
        assert.deepEqual((await requests('UpdateUser'))[0].variables.input.institutionIds, [])
        console.log('PASS: removing the last institution requires confirmation and sends an empty list')

        for (const selected of [[], ['Banco A', 'Banco B']]) {
            await page.goto(`${url}/?screen=create`)
            await page.locator('#name').fill('Nuevo usuario')
            await page.locator('#email').fill('nuevo@example.test')
            await page.locator('#password').fill('a long test passphrase')
            await page.locator('#confirm-password').fill('a long test passphrase')
            await page.locator('#role').fill('Analista')
            await page.getByRole('option', { name: 'Analista' }).click()
            for (const institution of selected) {
                await page.getByRole('button', { name: 'Seleccionar opciones' }).click()
                await page.getByRole('option', { name: institution }).click()
            }
            await page.getByRole('button', { name: 'Crear', exact: true }).click()
            await page.waitForFunction(() => window.institutionTestRequests.some((request) => request.name === 'CreateUser'))
            assert.equal((await requests('CreateUser'))[0].variables.input.institutionIds.length, selected.length)
        }
        console.log('PASS: creating users with zero and multiple institutions')

        await page.goto(`${url}/?screen=valuations`)
        const ownRow = page.getByRole('row').filter({ hasText: 'PROPIA' })
        const externalRow = page.getByRole('row').filter({ hasText: 'EXTERNA' })
        assert.equal(await ownRow.getByRole('button').count(), 1)
        assert.equal(await externalRow.getByRole('button').count(), 0)
        assert.equal(await externalRow.getByText('Solo lectura').count(), 1)
        console.log('PASS: authorized valuation keeps edit action, external valuation has none')
        await page.goto(`${url}/?screen=samples`)
        await page.getByRole('button', { name: 'Muestra (2)', exact: true }).click()
        await page.getByRole('link', { name: 'PROPIA', exact: true }).waitFor()
        assert.equal(await page.getByRole('columnheader').count(), 4)
        assert.equal(await page.getByRole('link', { name: 'EXTERNA', exact: true }).count(), 0)
        assert.equal(await page.getByRole('link', { name: 'PROPIA', exact: true }).getAttribute('href'), '/inmuebles/1/editar?valuation=1#valuaciones')
        await page.screenshot({ path: path.join(tmp, 'samples-mobile.png') })
        await page.goto(`${url}/?screen=samples&global=1`)
        await page.getByRole('button', { name: 'Muestra (2)', exact: true }).click()
        await page.getByRole('link', { name: 'EXTERNA', exact: true }).waitFor()
        assert.equal(await page.getByRole('columnheader').count(), 4)
        await page.goto(`${url}/?screen=samples&admin=1`)
        await page.getByRole('button', { name: 'Muestra (2)', exact: true }).click()
        assert.equal(await page.getByRole('columnheader').count(), 11)
        console.log('PASS: reduced sample columns, authorized links, global access and full administrator table')
        await page.goto(`${url}/?screen=valuation-detail`)
        await page.getByRole('dialog').waitFor()
        assert.equal(await page.getByRole('dialog').getByText('PROPIA', { exact: true }).count(), 1)
        assert.equal(await page.getByRole('dialog').getByRole('button', { name: /Guardar|Eliminar|Actualizar/ }).count(), 0)
        await page.screenshot({ path: path.join(tmp, 'valuation-detail-mobile.png') })
        await page.getByRole('button', { name: 'Cerrar detalle' }).click()
        await page.getByRole('dialog').waitFor({ state: 'detached' })
        assert.equal(await page.getByRole('dialog').count(), 0)
        await page.goto(`${url}/?screen=valuation-detail&valuation=2`)
        await page.getByText('La valuación no está disponible o no tiene permiso para consultarla.').waitFor()
        assert.equal(await page.getByRole('dialog').getByText('EXTERNA', { exact: true }).count(), 0)
        console.log('PASS: valuation deep link opens readonly detail and rejects unavailable valuations')
        await page.setViewportSize({ width: 1280, height: 900 })
        await page.goto(`${url}/?screen=history`)
        await page.getByRole('region', { name: 'Indicadores históricos' }).waitFor()
        assert.equal(await page.getByText('Inmueble: INMO000656', { exact: true }).count(), 1)
        assert.equal(await page.getByRole('img', { name: 'Gráfica histórica' }).count(), 0)
        await page.getByRole('button', { name: /Variación del valor/ }).click()
        await page.getByRole('img', { name: 'Gráfica histórica' }).waitFor()
        assert.equal(await page.getByText('+25.0%', { exact: true }).count(), 1)
        assert.equal(await page.locator('svg title').filter({ hasText: 'Financiera' }).count(), 2)
        await page.screenshot({ path: path.join(tmp, 'history-desktop.png') })
        await page.getByRole('button', { name: /Evolución del riesgo/ }).click()
        assert.equal(await page.getByRole('img', { name: 'Gráfica histórica' }).count(), 1)
        assert.equal(await page.getByText('El riesgo aumentó', { exact: true }).count(), 1)
        await page.setViewportSize({ width: 390, height: 844 })
        assert.equal(await page.getByRole('region', { name: 'Indicadores históricos' }).count(), 1)
        await page.screenshot({ path: path.join(tmp, 'history-mobile.png') })
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
        await page.getByRole('button', { name: 'Añadir', exact: true }).click()
        await page.getByRole('heading', { name: 'Agregar Valuación' }).waitFor()
        assert.equal(await page.getByText('Inmueble: INMO000656', { exact: true }).count(), 2)
        console.log('PASS: historical cards, exclusive expandable charts, dated tooltips, mobile width and property context')
        await page.goto(url)
        const historyLink = page.getByRole('link', { name: 'INMO000001' })
        await historyLink.waitFor()
        assert.equal(await historyLink.getAttribute('href'), '/inmuebles/1/editar#valuaciones')
        await historyLink.hover()
        await page.getByRole('tooltip', { name: 'Ver historial' }).waitFor()
        await page.getByText('1 de Junio de 2026', { exact: true }).waitFor()
        assert.equal(await page.getByText('Perfil de Riesgo:', { exact: true }).count(), 0)
        await page.goto(`${url}/?noaccess=1`)
        await page.getByText('INMO000001', { exact: true }).waitFor()
        assert.equal(await page.getByRole('link', { name: 'INMO000001' }).count(), 0)
        console.log('PASS: readonly history link, tooltip, authorized latest date and disabled institutional access')
        await page.setViewportSize({ width: 1280, height: 900 })
        await page.goto(`${url}/?screen=property-index`)
        await page.getByRole('searchbox', { name: 'Buscar' }).fill('INMO')
        await page.waitForFunction(() => window.institutionTestRequests.some(request => request.name === 'ListProperties' && request.variables.search === 'INMO'))
        await page.locator('#currentPage').fill('2')
        await page.locator('#currentPage').blur()
        await page.waitForFunction(() => window.institutionTestRequests.some(request => request.name === 'ListProperties' && request.variables.page === 2))
        await page.getByRole('button', { name: 'Filtros', exact: true }).click()
        await page.getByRole('combobox').click()
        await page.getByRole('option', { name: '2024', exact: true }).click()
        await page.getByRole('button', { name: 'Close', exact: true }).click()
        assert.equal((await requests('ListProperties')).some(request => request.variables.valuationYear), false)
        await page.getByRole('button', { name: 'Filtros', exact: true }).click()
        await page.getByRole('combobox').click()
        await page.getByRole('option', { name: '2024', exact: true }).click()
        await page.getByRole('button', { name: 'Aplicar filtros' }).click()
        await page.waitForFunction(() => window.institutionTestRequests.some(request => request.name === 'ListProperties' && request.variables.valuationYear === 2024 && request.variables.page === 1 && request.variables.search === 'INMO'))
        await page.getByRole('button', { name: /Filtros\s*2024/ }).click()
        await page.waitForFunction(() => document.querySelector('[role="combobox"]')?.textContent === '2024')
        assert.equal(await page.getByRole('combobox').textContent(), '2024')
        await page.getByRole('button', { name: 'Limpiar filtros' }).click()
        await page.getByRole('button', { name: 'Filtros', exact: true }).waitFor()
        assert.equal(await page.getByRole('searchbox', { name: 'Buscar' }).inputValue(), 'INMO')
        assert.equal(await page.locator('#currentPage').inputValue(), '1')
        await page.screenshot({ path: path.join(tmp, 'property-index-desktop.png') })
        console.log('PASS: filter cancel, apply, selected year persistence and clearing')
        await page.goto(`${url}/?screen=property-general`)
        const code = page.getByLabel('Referencia')
        await code.waitFor()
        assert.equal(await code.inputValue(), 'INMO000656')
        assert.equal(await code.evaluate(element => element.readOnly), true)
        await page.getByRole('button', { name: 'Guardar', exact: true }).click()
        await page.waitForFunction(() => window.institutionTestRequests.some(request => request.name === 'UpdateProperty'))
        const update = (await requests('UpdateProperty')).at(-1).variables.input
        assert.equal(Object.hasOwn(update, 'name'), false)
        assert.equal(update.id, '1')
        console.log('PASS: real property code readonly and excluded from update mutation')
        assert.deepEqual(errors, [])
        console.log(`Screenshots: ${tmp}`)
    } finally {
        if (browser) await browser.close()
        if (server) await new Promise((resolve) => server.close(resolve))
    }
}

main().catch((error) => { console.error(error); process.exitCode = 1 })
